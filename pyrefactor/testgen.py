"""Draft a pytest module for a freshly extracted function.

The draft is deliberately honest: it knows the signature, what the block
returns, which ``self`` attributes it touches and how each argument is used,
but not the *expected values*. Those are left as TODOs and the tests are
marked ``skip`` so an unfinished draft never breaks the suite.
"""
from __future__ import annotations

import builtins
import os
import pickle
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .extract import ExtractResult
from .typeinfer import TypeGuess, split_generic

_LITERALS = {
    "int": "0", "float": "0.0", "complex": "0j", "str": '""', "bytes": 'b""', "bool": "False", "None": "None",
    "list": "[]", "List": "[]", "Sequence": "[]", "Iterable": "[]", "deque": "[]",
    "dict": "{}", "Dict": "{}", "Mapping": "{}", "OrderedDict": "{}", "defaultdict": "{}", "Counter": "{}",
    "set": "set()", "Set": "set()", "frozenset": "frozenset()", "tuple": "()", "Tuple": "()",
}


def _placeholder_for(guess: TypeGuess, hints: List[str]) -> str:
    """An empty value of the suggested type; falls back to how the block uses the argument."""
    first = guess.type.split(" | ")[0]
    lit = _LITERALS.get(split_generic(first)[0])
    if lit is not None and guess.how != "unknown":
        return lit
    return _placeholder(hints)


def _placeholder(hints: List[str]) -> str:
    if any(h in ("iterated", "len(...)") or h.startswith(".append") for h in hints):
        return "[]"
    if any(h.startswith("[") and h != "[...]" and not h[1:2].isdigit() for h in hints):
        return "{}"
    if any(h.startswith((".items", ".get", ".keys", ".values", ".setdefault")) for h in hints):
        return "{}"
    if "arithmetic" in hints or "compared" in hints:
        return "0"
    return "None"


def _comment(guess: TypeGuess, hints: List[str]) -> str:
    text = f"  # TODO: realistic {guess.label}"
    if guess.how.startswith("guessed"):
        text += " (type guessed)"
    elif guess.how == "unknown":
        text = "  # TODO: realistic value (type unknown)"
    return text + (f"; used as: {', '.join(hints)}" if hints else "")


def default_test_path(target: Path, func_name: str, tests_dir: Optional[Path] = None) -> Path:
    tests_dir = tests_dir or target.parent / "tests"
    path = tests_dir / f"test_{target.stem}_{func_name}.py"
    n = 2
    while path.exists():  # never overwrite a test someone may have edited
        path = tests_dir / f"test_{target.stem}_{func_name}_{n}.py"
        n += 1
    return path


def render_test(result: ExtractResult, target: Path, test_path: Path) -> str:
    plan = result.plan
    name = result.name
    module = target.stem
    is_member = plan.kind != "function"
    cls_name = plan.class_qualname.split(".")[0] if is_member else ""
    import_name = cls_name if is_member else name

    # directory of the module, relative to the test file, so the draft keeps working if the project moves
    rel = os.path.relpath(target.parent.resolve(), test_path.parent.resolve())
    path_expr = "Path(__file__).resolve().parent" if rel == "." else f"(Path(__file__).resolve().parent / {Path(rel).as_posix()!r})"

    # original param name -> final param name, plus how the block uses it
    arg_lines = []
    for orig, final in zip(plan.params, result.params):
        hints = plan.param_hints.get(orig, [])
        guess = plan.param_types.get(orig) or TypeGuess("Any", "unknown")
        arg_lines.append(f"    {final} = {_placeholder_for(guess, hints)}{_comment(guess, hints)}")
    args = ", ".join(result.params)

    if plan.kind in ("method", "classmethod"):
        call_owner = "obj" if plan.kind == "method" else cls_name
    elif plan.kind == "staticmethod":
        call_owner = cls_name
    else:
        call_owner = ""
    callee = f"{call_owner}.{name}" if call_owner else name

    out: List[str] = []
    w = out.append
    w(f'"""Draft unit tests for `{plan.class_qualname + "." if is_member else ""}{name}`.')
    w("")
    w(f"Generated by pyrefactor when `{name}` was extracted from `{plan.qualname}`")
    w(f"({target.name}, originally lines {plan.source_start}-{plan.source_end}).")
    w("")
    w("This is a DRAFT. pyrefactor knows the signature, the return values and how each")
    w("argument is used, but not the expected results. Fill in the TODOs, then delete")
    w("the `skip` markers.")
    w("")
    w("Tip (characterization test): to get realistic values, temporarily print the")
    w(f"arguments and the result at the call site in `{plan.qualname}`, run the program")
    w("once, and paste them below. That pins down today's behaviour before you change it.")
    w('"""')
    w("import sys")
    w("from pathlib import Path")
    w("")
    w("import pytest")
    w("")
    w(f"sys.path.insert(0, str({path_expr}))  # make `{module}` importable")
    w("")
    w(f"from {module} import {import_name}  # noqa: E402")
    w("")
    w("")

    if plan.kind == "method":
        w(f"def _make_{cls_name.lower()}():")
        w(f'    """A `{cls_name}` with only the state `{name}` touches (bypasses __init__)."""')
        w(f"    obj = {cls_name}.__new__({cls_name})")
        if plan.self_attrs_read:
            for attr in plan.self_attrs_read:
                w(f"    obj.{attr} = None  # TODO: read by `{name}`")
        else:
            w(f"    # `{name}` reads no plain attributes of self; it may call other methods.")
        w("    return obj")
        w("")
        w("")

    def emit_test(test_name: str, title: str) -> None:
        w('@pytest.mark.skip(reason="draft: fill in inputs and expected values")')
        w(f"def {test_name}():")
        w(f'    """{title}"""')
        if plan.kind == "method":
            w(f"    obj = _make_{cls_name.lower()}()")
        w("    # Arrange")
        if arg_lines:
            out.extend(arg_lines)
        else:
            w("    # (no arguments: the block only depends on self/global state)")
        w("")
        w("    # Act")
        if plan.returns:
            w(f"    result = {callee}({args})")
        else:
            w(f"    {callee}({args})")
        w("")
        w("    # Assert")
        rtype = {r: plan.return_types[r].label if r in plan.return_types else "Any" for r in plan.returns}
        if len(plan.returns) == 1:
            r = plan.returns[0]
            w(f"    # The block computes `{r}` ({rtype[r]}), which the caller uses afterwards.")
            w(f"    assert result == ...  # TODO: expected {r} ({rtype[r]})")
        elif plan.returns:
            w(f"    # The block computes {', '.join('`%s`' % r for r in plan.returns)}, returned as {plan.returns_type}.")
            w(f"    {', '.join(plan.returns)} = result")
            for r in plan.returns:
                w(f"    assert {r} == ...  # TODO: expected {r} ({rtype[r]})")
        else:
            w("    # The block returns nothing: it works through side effects. Assert on them, e.g.:")
            mutated = [
                final
                for orig, final in zip(plan.params, result.params)
                if any(h.endswith("()") and h.startswith(".") for h in plan.param_hints.get(orig, []))
            ]
            for m in mutated:
                w(f"    assert {m} == ...  # TODO: state of `{m}` after the call (mutating methods are called on it)")
            if not mutated:
                w("    # captured output (use the `capsys` fixture), mutated arguments, or changed object state.")
                w("    assert True  # TODO")
        if plan.kind == "method" and plan.self_attrs_written:
            for attr in plan.self_attrs_written:
                w(f"    assert obj.{attr} == ...  # TODO: `{name}` assigns self.{attr}")
        w("")
        w("")

    emit_test(f"test_{name}_typical_case", "Happy path with representative inputs.")

    # parametrized edge cases
    w('@pytest.mark.skip(reason="draft: add edge cases")')
    params_csv = ", ".join(result.params + (["expected"] if plan.returns else []))
    if params_csv:
        w(f'@pytest.mark.parametrize("{params_csv}", [')
        w(f"    # TODO: ({params_csv}),")
        ideas = []
        for orig, final in zip(plan.params, result.params):
            hints = plan.param_hints.get(orig, [])
            ph = _placeholder_for(plan.param_types.get(orig) or TypeGuess("Any", "unknown"), hints)
            if ph in ("[]", "{}"):
                ideas.append(f"empty `{final}`")
            elif ph in ("0", "0.0"):
                ideas.append(f"zero/negative `{final}`")
            elif "truth-tested" in hints:
                ideas.append(f"falsy `{final}`")
            else:
                ideas.append(f"`{final}` missing optional fields")
        if ideas:
            w(f"    # Ideas: {'; '.join(ideas)}.")
        w("])")
        w(f"def test_{name}_edge_cases({params_csv}):")
    else:
        w(f"def test_{name}_edge_cases():")
    w('    """Boundary conditions: empty inputs, zero values, unusual branches."""')
    if plan.kind == "method":
        w(f"    obj = _make_{cls_name.lower()}()")
    if plan.returns:
        w(f"    assert {callee}({args}) == expected")
    else:
        w(f"    {callee}({args})  # TODO: assert on side effects")
    w("")
    return "\n".join(out)


_SAME_HELPER = '''

def _same(a, b):
    """Equal data, also for objects without __eq__ (compared field by field)."""
    return _shape(a) == _shape(b)


def _shape(x, depth=0):
    if depth > 50 or isinstance(x, (str, bytes, int, float, complex, bool, type(None))):
        return x
    d = depth + 1
    if isinstance(x, dict):
        return (type(x).__name__, sorted(((repr(k), _shape(v, d)) for k, v in x.items()), key=lambda t: t[0]))
    if isinstance(x, (list, tuple)):
        return (type(x).__name__, [_shape(v, d) for v in x])
    if isinstance(x, (set, frozenset)):
        return (type(x).__name__, sorted(repr(_shape(v, d)) for v in x))
    fields = getattr(x, "__dict__", None)
    if fields is None and hasattr(type(x), "__slots__"):
        fields = {s: getattr(x, s) for s in type(x).__slots__ if hasattr(x, s)}
    if fields is not None:
        return (type(x).__qualname__, _shape(dict(fields), d))
    return (type(x).__qualname__, repr(x))
'''


def render_recorded_test(result: ExtractResult, target: Path, test_path: Path, rec) -> Tuple[str, Dict]:
    """A runnable test per recorded code path. Returns (source, data) where ``data`` holds the values
    too complex to write inline, as pickled bytes keyed by case number."""
    plan = result.plan
    name = result.name
    module = target.stem
    cls_name = plan.class_qualname.split(".")[0] if plan.kind != "function" else ""
    self_name = plan.self_name if plan.kind in ("method", "classmethod") else None
    rel = os.path.relpath(target.parent.resolve(), test_path.parent.resolve())
    path_expr = "Path(__file__).resolve().parent" if rel == "." else f"(Path(__file__).resolve().parent / {Path(rel).as_posix()!r})"

    data: Dict[int, Dict[str, bytes]] = {}
    imports_from_module = {cls_name or name}
    uses = {"datetime": False, "same": False, "re": False}
    collections_names: set = set()

    def value_expr(i: int, key: str, v: dict) -> Tuple[str, str]:
        """(python expression, trailing comment) for a recorded value."""
        r = v.get("repr")
        if r is not None:
            imports_from_module.update(v.get("names", []))
            if "datetime." in r:
                uses["datetime"] = True
            for c in ("OrderedDict", "Counter", "deque"):
                if c + "(" in r:
                    collections_names.add(c)
            if "Decimal(" in r:
                collections_names.add("Decimal")
            return r, ""
        data.setdefault(i, {})[key] = v["pickle"]
        return f"_recorded({i}, {key!r})", f"  # {v['type']}: too complex to write inline"

    body: List[str] = []
    w = body.append
    total = len(rec.cases)
    for i, case in enumerate(rec.cases, 1):
        args = case["args"]
        needs_capsys = bool(case["stdout"])
        w("")
        w("")
        w(f"def test_{name}_recorded_{i}({'capsys' if needs_capsys else ''}):")
        w(f'    """Call #{case["call"]} of {rec.calls} while running `{rec.command}` '
          f'(code path {i} of {total})."""')
        call_args = []
        if case.get("bundle"):
            data.setdefault(i, {})["args"] = case["bundle"]
            w(f"    recorded = _recorded({i}, 'args')  # loaded together: objects shared between arguments stay shared")

        def arg_expr(arg: str) -> Tuple[str, str]:
            if args[arg].get("repr") is None:
                return f"recorded[{arg!r}]", f"  # {args[arg]['type']}"
            return value_expr(i, arg, args[arg])

        for arg in (p for p in args if p != self_name):  # recorded under the function's own parameter names
            expr, note = arg_expr(arg)
            w(f"    {arg} = {expr}{note}")
            call_args.append(arg)
        if plan.kind == "method":
            expr, note = arg_expr(self_name)
            w(f"    obj = {expr}{note}")
            callee = f"obj.{name}"
        elif plan.kind in ("staticmethod", "classmethod"):
            callee = f"{cls_name}.{name}"
        else:
            callee = name
        call = f"{callee}({', '.join(call_args)})"
        w("")
        if case["exc"] is not None:
            exc_type, msg = case["exc"]
            uses["re"] = True
            builtin = isinstance(getattr(builtins, exc_type, None), type)
            exc_expr = exc_type if builtin else f"{module}_{exc_type}"
            if not builtin:
                imports_from_module.add(f"{exc_type} as {module}_{exc_type}")
            w(f"    with pytest.raises({exc_expr}, match=re.escape({msg!r})):")
            w(f"        {call}")
        elif plan.returns:
            w(f"    result = {call}")
            w("")
            res = case["result"]
            if res.get("repr") is not None and res.get("eq"):
                expr, _ = value_expr(i, "result", res)
                w(f"    assert result == {expr}")
            else:
                expr, note = value_expr(i, "result", {**res, "repr": None})
                uses["same"] = True
                w(f"    assert _same(result, {expr}){note}")
        else:
            w(f"    {call}")
            w("")
        for key, after in case["after"].items():
            target_name = "obj" if key == self_name else key
            what = "state of the object afterwards" if key == self_name else "changed in place"
            if after.get("repr") is not None and after.get("eq"):
                expr, _ = value_expr(i, "after:" + key, after)
                w(f"    assert {target_name} == {expr}  # {what}")
            else:
                expr, _ = value_expr(i, "after:" + key, {**after, "repr": None})
                uses["same"] = True
                w(f"    assert _same({target_name}, {expr})  # {what}")
        if needs_capsys:
            out = case["stdout"]
            if len(out) <= 300:
                w(f"    assert capsys.readouterr().out == {out!r}")
            else:
                data.setdefault(i, {})["stdout"] = pickle.dumps(out)
                w(f"    assert capsys.readouterr().out == _recorded({i}, 'stdout')  # {len(out)} characters")
        if not case["after"] and not plan.returns and not needs_capsys and case["exc"] is None:
            w("    # The recorded call changed none of its arguments and printed nothing.")

    head: List[str] = []
    h = head.append
    h(f'"""Characterization tests for `{plan.class_qualname + "." if cls_name else ""}{name}`.')
    h("")
    h(f"Generated by pyrefactor when `{name}` was extracted from `{plan.qualname}`")
    h(f"({target.name}, originally lines {plan.source_start}-{plan.source_end}).")
    h("")
    h(f"The values below were recorded from a real run of `{rec.command}`: the function ran")
    h(f"{rec.calls} time(s); each test pins one distinct code path (inputs, result, in-place changes and")
    h("printed output). They run on their own, without the program. If you change the function's")
    h("behaviour on purpose, update the expected values.")
    h('"""')
    if uses["datetime"]:
        h("import datetime")
    if data:
        h("import pickle")
    if uses["re"]:
        h("import re")
    h("import sys")
    if collections_names - {"Decimal"}:
        h(f"from collections import {', '.join(sorted(collections_names - {'Decimal'}))}")
    if "Decimal" in collections_names:
        h("from decimal import Decimal")
    h("from pathlib import Path")
    h("")
    h("import pytest  # noqa: F401")
    h("")
    h(f"sys.path.insert(0, str({path_expr}))  # make `{module}` importable")
    h("")
    h(f"from {module} import {', '.join(sorted(imports_from_module))}  # noqa: E402")
    if data:
        h("")
        h(f"_DATA = Path(__file__).resolve().parent / \"data\" / {test_path.stem + '.pkl'!r}")
        h("_RECORDED = pickle.loads(_DATA.read_bytes())  # case number -> name -> pickled value")
        h("")
        h("")
        h("def _recorded(case, key):")
        h('    """A fresh copy of a recorded value (tests may change it freely)."""')
        h("    return pickle.loads(_RECORDED[case][key])")
    text = "\n".join(head)
    if uses["same"]:
        text += "\n" + _SAME_HELPER.rstrip("\n")
    text += "\n" + "\n".join(body) + "\n"
    return text, data


def write_test(result: ExtractResult, target: Path, tests_dir: Optional[Path] = None, recording=None) -> Path:
    """Write a runnable characterization test when ``recording`` holds real calls, else a draft."""
    path = default_test_path(target, result.name, tests_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    if recording is not None and recording.ok:
        text, data = render_recorded_test(result, target, path, recording)
        compile(text, str(path), "exec")
        if data:
            data_path = path.parent / "data" / (path.stem + ".pkl")
            data_path.parent.mkdir(parents=True, exist_ok=True)
            data_path.write_bytes(pickle.dumps(data, protocol=4))
    else:
        text = render_test(result, target, path)
        if recording is not None and recording.problem:
            text = text.replace('"""\nimport sys', f'\nNo values could be recorded: {recording.problem}.\n"""\nimport sys', 1)
        compile(text, str(path), "exec")  # the draft must at least be valid Python
    path.write_text(text, encoding="utf-8")
    return path
